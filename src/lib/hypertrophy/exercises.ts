export function findExerciseFuzzy(query: string): ExerciseDefinition {
  const q = (query || '').toLowerCase().trim();
  const exact = EXERCISES.find(
    (e) => e.id.toLowerCase() === q || e.name.toLowerCase() === q
  );
  if (exact) return exact;
  if (q.includes('chin') || q.includes('trazioni')) {
    return getExerciseById('weighted-chin-up');
  }
  if (q.includes('pull-up') || q.includes('pullup')) {
    return getExerciseById('weighted-pull-up');
  }
  if (q.includes('pulley') || q.includes('pulldown') || q.includes('lat')) {
    return getExerciseById('lat-pulldown-pulley');
  }
  if (q.includes('incline') && q.includes('db')) {
    return getExerciseById('incline-db-press');
  }
  if (q.includes('bench') || q.includes('panca')) {
    return getExerciseById('barbell-bench-press');
  }
  if (q.includes('squat') && q.includes('hack')) {
    return getExerciseById('hack-squat');
  }
  if (q.includes('squat')) {
    return getExerciseById('barbell-back-squat');
  }
  if (q.includes('rdl') || q.includes('romanian') || q.includes('deadlift')) {
    return getExerciseById('romanian-deadlift');
  }
  const partial = EXERCISES.find(
    (e) => e.name.toLowerCase().includes(q) || e.id.toLowerCase().includes(q)
  );
  return partial || EXERCISES[0];
}

